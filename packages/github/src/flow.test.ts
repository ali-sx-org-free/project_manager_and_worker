  const { pm, gh, hubName, worker } = world();
  await pm.init();
  const { tasks } = await pm.createProject(plan({ tasks: [{ key: 'a', title: 'A' }, { key: 'b', title: 'B' }] }));
  const alice = worker('alice', 'alice-pc');
