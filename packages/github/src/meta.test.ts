import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readBodyBlock, taskBody, writeBodyBlock } from './meta.ts';

/** 有些環境（例如 Claude Code 雲端會話）寫 Issue 時，會自動在正文最後加一段頁腳 */
const FOOTER = '\n\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const block = { key: 'greet', project: 2, deps: [], caps: [] };
const plain = writeBodyBlock(taskBody('寫一個打招呼的頁面', '- 打開首頁看到「你好」'), 'apm:task', block);

test('正文區塊：沒有頁腳時照舊', () => {
  const r = readBodyBlock(plain, 'apm:task');
  assert.deepEqual(r.data, block);
  assert.match(r.rest, /^## 說明\n\n寫一個打招呼的頁面/);
  assert.match(r.rest, /驗收標準\n\n- 打開首頁看到「你好」$/);
});

test('正文區塊：--> 後面有頁腳也讀得到，rest 不含頁腳', () => {
  // 和驗收時 hub 上 Issue #3 的結尾一樣
  const body = `${plain}${FOOTER}`;
  assert.ok(body.endsWith('-->\n\n\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'));
  const r = readBodyBlock(body, 'apm:task');
  assert.deepEqual(r.data, block);
  assert.equal(r.rest, readBodyBlock(plain, 'apm:task').rest);
  assert.doesNotMatch(r.rest, /Generated by/);
  // Windows 換行、頁腳後面還有空白也一樣
  assert.deepEqual(readBodyBlock(`${plain.replace(/\n/g, '\r\n')}${FOOTER}  \n`, 'apm:task').data, block);
});

test('正文區塊：說明裡引用了一段區塊時，讀最後一個', () => {
  const quoted = taskBody('把舊格式\n\n<!-- apm:task\nkey: old\nproject: 1\n-->\n\n換成新的', '- 完成');
  const body = writeBodyBlock(quoted, 'apm:task', block);
  const r = readBodyBlock(`${body}${FOOTER}`, 'apm:task');
  assert.deepEqual(r.data, block);
  assert.match(r.rest, /key: old/); // 引用的那段是說明的一部分
  // 只引用了開頭、沒有收尾的半個區塊，也不會從那裡一路吃到真正的區塊
  const half = writeBodyBlock(taskBody('提到 <!-- apm:task 這個標記', ''), 'apm:task', block);
  const h = readBodyBlock(half, 'apm:task');
  assert.deepEqual(h.data, block);
  assert.match(h.rest, /提到 <!-- apm:task 這個標記/);
});

test('正文區塊：讀了再寫回，頁腳被去掉，區塊在最後', () => {
  const r = readBodyBlock(`${plain}${FOOTER}`, 'apm:task');
  const again = writeBodyBlock(r.rest, 'apm:task', { ...block, deps: [7] });
  assert.doesNotMatch(again, /Generated by/);
  assert.match(again, /-->\n$/);
  assert.deepEqual(readBodyBlock(again, 'apm:task').data, { ...block, deps: [7] });
  // 環境每次寫都再加一次頁腳，也不會越疊越多
  const third = writeBodyBlock(readBodyBlock(`${again}${FOOTER}`, 'apm:task').rest, 'apm:task', block);
  assert.equal(third, plain);
});

test('正文區塊：沒有區塊、空正文', () => {
  assert.deepEqual(readBodyBlock(`普通 Issue${FOOTER}`, 'apm:task'), { data: null, rest: `普通 Issue${FOOTER}`.trim() });
  assert.deepEqual(readBodyBlock(null, 'apm:task'), { data: null, rest: '' });
  // 標籤不同的區塊不算
  assert.equal(readBodyBlock(plain, 'apm:project').data, null);
});
